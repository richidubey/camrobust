from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy import stats

METHOD_ORDER = ["erm", "colorjitter", "cameraaug", "pair", "consistency", "bacc"]
METHOD_LABELS = {
    "erm": "ERM",
    "colorjitter": "ColorJitter",
    "cameraaug": "CameraAug",
    "pair": "Paired CameraAug",
    "consistency": "Uniform consistency",
    "bacc": "BaCC",
}


def load_runs(root: Path) -> pd.DataFrame:
    rows = []
    for path in sorted(root.glob("*/metrics.json")):
        payload = json.loads(path.read_text())
        config = payload["config"]
        aggregate = payload["test"]["aggregate"]
        row = {
            "run_name": payload["run_name"],
            "architecture": config["architecture"],
            "method": config["method"],
            "budget": config["budget"],
            "seed": config["seed"],
            "boundary_alpha": config["boundary_alpha"],
            "best_val_miou": payload["best_val_miou"],
            "elapsed_seconds": payload["elapsed_seconds"],
            **{k: v for k, v in aggregate.items() if isinstance(v, (int, float))},
        }
        for corruption, value in aggregate["per_corruption_miou"].items():
            row[f"corr_{corruption}"] = value
        for sequence, value in payload["test"]["conditions"]["clean"].get("sequence_metrics", {}).items():
            row[f"seq_{sequence}_miou"] = value["miou"]
        rows.append(row)
    if not rows:
        raise FileNotFoundError(f"no metrics.json files under {root}")
    return pd.DataFrame(rows)


def mean_ci(values: pd.Series) -> tuple[float, float]:
    x = values.dropna().to_numpy(float)
    if len(x) < 2:
        return float(np.mean(x)), float("nan")
    sem = stats.sem(x)
    return float(np.mean(x)), float(stats.t.ppf(0.975, len(x) - 1) * sem)


def paired_factor_tests(df: pd.DataFrame) -> pd.DataFrame:
    """Paired, exploratory tests for each adjacent factor in the design.

    Subset seed is the pairing unit.  With only three seeds, these rows are
    intended to expose effect direction and variability, not to support a
    binary significance narrative.
    """
    rows = []
    main = df[(df.architecture == "deeplab") & (df.boundary_alpha == 3.0)]
    comparisons = [
        ("CameraAug - ERM", "cameraaug", "erm"),
        ("Paired - CameraAug", "pair", "cameraaug"),
        ("Uniform consistency - paired", "consistency", "pair"),
        ("BaCC - uniform consistency", "bacc", "consistency"),
    ]
    metrics = {
        "clean_miou": "Clean mIoU",
        "miou_c": "mIoU-C",
        "unseen_miou_c": "Held-out mIoU-C",
        "mean_boundary_f1_c": "Boundary F1-C",
        "mean_ece_c": "ECE-C",
    }
    for budget in sorted(main.budget.unique()):
        group = main[main.budget == budget]
        for metric, metric_label in metrics.items():
            pivot = group.pivot(index="seed", columns="method", values=metric)
            for comparison, treatment, control in comparisons:
                if not {treatment, control}.issubset(pivot.columns):
                    continue
                pair = pivot[[treatment, control]].dropna()
                delta = pair[treatment] - pair[control]
                t_result = stats.ttest_rel(pair[treatment], pair[control]) if len(pair) >= 2 else None
                std = delta.std(ddof=1)
                rows.append(
                    {
                        "budget": budget,
                        "metric": metric_label,
                        "comparison": comparison,
                        "n": len(pair),
                        "mean_delta": delta.mean(),
                        "std_delta": std,
                        "cohens_dz": delta.mean() / std if std > 0 else np.nan,
                        "wins": int((delta > 0).sum()),
                        "paired_t_p": t_result.pvalue if t_result else np.nan,
                    }
                )
    return pd.DataFrame(rows)


def write_latex_macros(summary: pd.DataFrame, path: Path) -> None:
    lines = ["% Generated by camrobust-analyze; do not edit by hand."]
    budget_words = {16: "Sixteen", 32: "ThirtyTwo", 64: "SixtyFour"}
    for _, row in summary.iterrows():
        method = str(row["method"]).replace("_", "").title()
        budget = int(row["budget"])
        if budget not in budget_words:
            raise ValueError(f"add a TeX-safe word for label budget {budget}")
        budget_word = budget_words[budget]
        lines.append(f"\\newcommand{{\\{method}Clean{budget_word}}}{{{100*row['clean_mean']:.1f}}}")
        lines.append(f"\\newcommand{{\\{method}Robust{budget_word}}}{{{100*row['robust_mean']:.1f}}}")
    path.write_text("\n".join(lines) + "\n")


def _pm(mean: float, ci: float, scale: float = 100.0) -> str:
    if np.isnan(ci):
        return f"{scale * mean:.1f}"
    return f"{scale * mean:.1f} $\\pm$ {scale * ci:.1f}"


def _pm_bold(mean: float, ci: float, bold: bool, scale: float = 100.0) -> str:
    value = f"{scale * mean:.1f}"
    if bold:
        value = f"\\textbf{{{value}}}"
    if np.isnan(ci):
        return value
    return f"{value} $\\pm$ {scale * ci:.1f}"


def _display_best(group: pd.DataFrame, column: str) -> set[str]:
    """Methods whose rounded displayed value ties the best in this budget block."""
    rounded = group.set_index("method")[column].map(lambda v: round(100 * v, 1))
    return set(rounded[rounded == rounded.max()].index)


def write_main_table(summary: pd.DataFrame, path: Path) -> None:
    lines = [
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Main CamVid results: mean $\\pm$ 95\\% $t$-interval over three "
        "nested-subset seeds (boundary F1: mean only). Bold marks the best value "
        "per column within each label budget; rounded ties share the bold. "
        "Worst-family mIoU and calibration for the same runs are tabulated in the "
        "supplementary.}",
        "\\label{tab:main}",
        "\\small",
        "\\setlength{\\tabcolsep}{4.5pt}",
        "\\begin{tabular}{clrrrr}",
        "\\toprule",
        "Labels & Method & Clean & \\miouc{} & Held-out & Bnd.\\ F1 \\\\",
        "\\midrule",
    ]
    budgets = sorted(summary.budget.unique())
    for bi, budget in enumerate(budgets):
        group = summary[summary.budget == budget]
        best = {
            "clean": _display_best(group, "clean_mean"),
            "robust": _display_best(group, "robust_mean"),
            "unseen": _display_best(group, "unseen_mean"),
            "boundary": _display_best(group, "boundary_f1_c"),
        }
        for ri, method in enumerate(METHOD_ORDER):
            row = group[group.method == method]
            if row.empty:
                continue
            r = row.iloc[0]
            label = METHOD_LABELS[method]
            prefix = f"\\multirow{{{len(group)}}}{{*}}{{{int(budget)}}}" if ri == 0 else ""
            lines.append(
                f"{prefix} & {label} & {_pm_bold(r.clean_mean, r.clean_ci95, method in best['clean'])} & "
                f"{_pm_bold(r.robust_mean, r.robust_ci95, method in best['robust'])} & "
                f"{_pm_bold(r.unseen_mean, r.unseen_ci95, method in best['unseen'])} & "
                f"{_pm_bold(r.boundary_f1_c, np.nan, method in best['boundary'])} \\\\"
            )
        if bi < len(budgets) - 1:
            lines.append("\\midrule")
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])
    path.write_text("\n".join(lines) + "\n")


def write_main_table_full(summary: pd.DataFrame, path: Path) -> None:
    lines = [
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Complete aggregate CamVid results. Values are mean $\\pm$ 95\\% "
        "$t$-interval over three nested-subset seeds. Worst is the lowest "
        "corruption-family mIoU; ECE is 15-bin expected calibration error under "
        "corruption (lower is better).}",
        "\\label{tab:main-full}",
        "\\small",
        "\\resizebox{\\linewidth}{!}{%",
        "\\begin{tabular}{clrrrrrr}",
        "\\toprule",
        "Labels & Method & Clean & \\miouc{} & Held-out & Worst & Boundary F1 & ECE \\\\",
        "\\midrule",
    ]
    budgets = sorted(summary.budget.unique())
    for bi, budget in enumerate(budgets):
        group = summary[summary.budget == budget]
        for ri, method in enumerate(METHOD_ORDER):
            row = group[group.method == method]
            if row.empty:
                continue
            r = row.iloc[0]
            label = METHOD_LABELS[method]
            prefix = f"\\multirow{{{len(group)}}}{{*}}{{{int(budget)}}}" if ri == 0 else ""
            lines.append(
                f"{prefix} & {label} & {_pm(r.clean_mean, r.clean_ci95)} & "
                f"{_pm(r.robust_mean, r.robust_ci95)} & {_pm(r.unseen_mean, r.unseen_ci95)} & "
                f"{100*r.get('worst_corruption_miou', np.nan):.1f} & {100*r.boundary_f1_c:.1f} & {100*r.ece_c:.1f} \\\\"
            )
        if bi < len(budgets) - 1:
            lines.append("\\midrule")
    lines.extend(["\\bottomrule", "\\end{tabular}}", "\\end{table*}"])
    path.write_text("\n".join(lines) + "\n")


def write_corruption_table(df: pd.DataFrame, path: Path) -> None:
    selected = df[
        (df.architecture == "deeplab")
        & (df.budget == 32)
        & (df.boundary_alpha == 3.0)
        & (df.method.isin(["erm", "cameraaug", "consistency", "bacc"]))
    ]
    columns = [c for c in selected.columns if c.startswith("corr_")]
    means = selected.groupby("method")[columns].mean()
    lines = [
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Per-corruption mIoU at 32 labels, averaged over three severities and three seeds. Shot noise, motion blur, and JPEG are absent from training.}",
        "\\label{tab:corruptions}",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2.5pt}",
        "\\begin{tabular}{l" + "r" * len(columns) + "}",
        "\\toprule",
        "Method & Bright. & Dark & Defocus & Gauss. & JPEG & Motion & Shot & W. bal. \\\\",
        "\\midrule",
    ]
    for method in ["erm", "cameraaug", "consistency", "bacc"]:
        if method not in means.index:
            continue
        values = " & ".join(f"{100*means.loc[method, c]:.1f}" for c in columns)
        label = "Uniform" if method == "consistency" else METHOD_LABELS[method]
        lines.append(f"{label} & {values} \\\\ ")
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table*}"])
    path.write_text("\n".join(lines) + "\n")


def write_ablation_table(df: pd.DataFrame, path: Path) -> None:
    rows = []
    primary = df[(df.architecture == "deeplab") & (df.budget == 32)]
    uniform = primary[primary.method == "consistency"].copy()
    if not uniform.empty:
        rows.append(("DeepLabV3", "$\\alpha=0$ (uniform)", uniform))
    for alpha in (1.0, 3.0, 6.0):
        group = primary[(primary.method == "bacc") & (primary.boundary_alpha == alpha)]
        if not group.empty:
            rows.append(("DeepLabV3", f"$\\alpha={alpha:g}$", group))
    for method in ("erm", "bacc"):
        group = df[(df.architecture == "lraspp") & (df.budget == 32) & (df.method == method)]
        if not group.empty:
            rows.append(("LR-ASPP", METHOD_LABELS[method], group))
    lines = [
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Boundary-weight ablation and architecture check at 32 labels. Mean over three seeds.}",
        "\\label{tab:ablation}",
        "\\small",
        "\\begin{tabular}{llrrr}",
        "\\toprule Architecture & Setting & Clean & \\miouc{} & Boundary F1 \\\\",
        "\\midrule",
    ]
    previous = None
    for architecture, setting, group in rows:
        if previous is not None and architecture != previous:
            lines.append("\\midrule")
        lines.append(
            f"{architecture} & {setting} & {100*group.clean_miou.mean():.1f} & "
            f"{100*group.miou_c.mean():.1f} & {100*group.mean_boundary_f1_c.mean():.1f} \\\\"
        )
        previous = architecture
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])
    path.write_text("\n".join(lines) + "\n")


def write_sequence_table(df: pd.DataFrame, path: Path) -> None:
    columns = [c for c in df.columns if c.startswith("seq_") and c.endswith("_miou")]
    selected = df[
        (df.architecture == "deeplab")
        & (df.budget == 32)
        & (df.boundary_alpha == 3.0)
        & (df.method.isin(["erm", "cameraaug", "consistency", "bacc"]))
    ]
    lines = [
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Clean test mIoU by source video sequence at 32 labels. Mean over three seeds.}",
        "\\label{tab:sequences}",
        "\\small",
        "\\begin{tabular}{l" + "r" * len(columns) + "}",
        "\\toprule",
        "Method & " + " & ".join(c.removeprefix("seq_").removesuffix("_miou") for c in columns) + " \\\\",
        "\\midrule",
    ]
    for method in ["erm", "cameraaug", "consistency", "bacc"]:
        group = selected[selected.method == method]
        if group.empty or not columns:
            continue
        lines.append(
            f"{METHOD_LABELS[method]} & " + " & ".join(f"{100*group[c].mean():.1f}" for c in columns) + " \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])
    path.write_text("\n".join(lines) + "\n")


def write_obstacle_class_table(runs_root: Path, path: Path) -> None:
    """Write corruption-averaged IoU for small or safety-relevant classes."""
    class_names = [
        "Sky", "Building", "Pole", "Road", "Pavement", "Tree",
        "Sign", "Fence", "Car", "Pedestrian", "Bicyclist",
    ]
    selected_indices = [2, 6, 8, 9, 10]
    records = []
    for metrics_path in sorted(runs_root.glob("*/metrics.json")):
        payload = json.loads(metrics_path.read_text())
        config = payload["config"]
        if not (
            config["architecture"] == "deeplab"
            and config["budget"] == 32
            and config["boundary_alpha"] == 3.0
            and config["method"] in {"erm", "pair", "consistency", "bacc"}
        ):
            continue
        corrupted = [
            condition["class_iou"]
            for name, condition in payload["test"]["conditions"].items()
            if name != "clean"
        ]
        values = np.nanmean(np.asarray(corrupted, dtype=float), axis=0)
        records.append({"method": config["method"], **{class_names[i]: values[i] for i in selected_indices}})
    frame = pd.DataFrame(records)
    means = frame.groupby("method").mean()
    lines = [
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Corruption-averaged IoU for thin and obstacle-relevant classes at 32 labels (24 conditions, three seeds).}",
        "\\label{tab:obstacle-classes}",
        "\\small",
        "\\begin{tabular}{lrrrrr}",
        "\\toprule Method & Pole & Sign & Car & Ped. & Bike \\\\",
        "\\midrule",
    ]
    for method in ["erm", "pair", "consistency", "bacc"]:
        if method not in means.index:
            continue
        values = " & ".join(f"{100 * means.loc[method, class_names[i]]:.1f}" for i in selected_indices)
        label = {"pair": "Paired", "consistency": "Uniform"}.get(method, METHOD_LABELS[method])
        lines.append(f"{label} & {values} \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="Aggregate CamRobust experiment records")
    parser.add_argument("--runs", default="results/runs")
    parser.add_argument("--output", default="results/aggregate")
    args = parser.parse_args()
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)
    df = load_runs(Path(args.runs))
    df.to_csv(output / "all_runs.csv", index=False)
    main_df = df[(df.architecture == "deeplab") & (df.boundary_alpha == 3.0)]
    records = []
    for (budget, method), group in main_df.groupby(["budget", "method"]):
        clean_mean, clean_ci = mean_ci(group.clean_miou)
        robust_mean, robust_ci = mean_ci(group.miou_c)
        unseen_mean, unseen_ci = mean_ci(group.unseen_miou_c)
        records.append(
            {
                "budget": budget,
                "method": method,
                "clean_mean": clean_mean,
                "clean_ci95": clean_ci,
                "robust_mean": robust_mean,
                "robust_ci95": robust_ci,
                "unseen_mean": unseen_mean,
                "unseen_ci95": unseen_ci,
                "boundary_f1_c": group.mean_boundary_f1_c.mean(),
                "ece_c": group.mean_ece_c.mean(),
                "worst_corruption_miou": group.worst_corruption_miou.mean(),
                "n": len(group),
            }
        )
    summary = pd.DataFrame(records)
    summary["method_rank"] = summary.method.map({m: i for i, m in enumerate(METHOD_ORDER)})
    summary = summary.sort_values(["budget", "method_rank"]).drop(columns="method_rank")
    summary.to_csv(output / "main_summary.csv", index=False)
    paired_factor_tests(df).to_csv(output / "paired_tests.csv", index=False)
    write_latex_macros(summary, output / "paper_macros.tex")
    write_main_table(summary, output / "table_main.tex")
    write_main_table_full(summary, output / "table_main_full.tex")
    write_corruption_table(df, output / "table_corruptions.tex")
    write_ablation_table(df, output / "table_ablation.tex")
    write_sequence_table(df, output / "table_sequences.tex")
    write_obstacle_class_table(Path(args.runs), output / "table_obstacle_classes.tex")

    fig, axes = plt.subplots(1, 2, figsize=(9.0, 3.5), constrained_layout=True)
    for method in METHOD_ORDER:
        group = summary[summary.method == method]
        if group.empty:
            continue
        axes[0].errorbar(
            group.budget,
            100 * group.robust_mean,
            yerr=100 * group.robust_ci95,
            marker="o",
            capsize=3,
            label=METHOD_LABELS[method],
        )
        axes[1].plot(100 * group.clean_mean, 100 * group.robust_mean, marker="o", label=METHOD_LABELS[method])
    axes[0].set(xlabel="Labeled training images", ylabel="mIoU-C (%)", xscale="log")
    axes[0].set_xticks([16, 32, 64], labels=["16", "32", "64"])
    axes[0].grid(alpha=0.25)
    axes[1].set(xlabel="Clean mIoU (%)", ylabel="mIoU-C (%)")
    axes[1].grid(alpha=0.25)
    axes[0].legend(fontsize=7, ncol=2)
    fig.savefig(output / "main_results.pdf", bbox_inches="tight")
    fig.savefig(output / "main_results.png", dpi=200, bbox_inches="tight")
    print(summary.to_string(index=False))


if __name__ == "__main__":
    main()
